package com.intelliworks.journey

import kotlinx.serialization.Serializable

/**
 * The runtime's node vocabulary (60 types), adopted as the primary planning type.
 * Mirrors FlowNodeType in the other project's flow/.../FlowModel.kt.
 */
@Serializable
enum class FlowCategory {
    JOURNEY_CONTROL, COMMUNICATE, DECIDE, AI, ACCESS, WAIT_TIMING,
    PERSONALIZE, GOVERN, INTEGRATE, UPDATE_DATA, MEASURE,
}

@Serializable
enum class FlowNodeType {
    // Journey control (6)
    START_TRIGGER, EXIT_JOURNEY, PAUSE_JOURNEY, RE_ENTER, JUMP_TO_STEP, STOP_CAMPAIGNS,
    // Communicate (8)
    SEND_EMAIL, SEND_SMS, SEND_PUSH, SEND_WHATSAPP, SEND_IN_APP, WEB_PERSONAL,
    CALL_CENTER_TASK, DIRECT_MAIL,
    // Decide (8)
    IF_ELSE, AUDIENCE_CHECK, ELIGIBILITY_CHECK, AB_SPLIT, RANDOM_SPLIT, CONTROL_GROUP,
    ML_DECISION, NEXT_BEST_CHANNEL,
    // AI (2)
    SCORE, RECOMMEND,
    // Access (4)
    ACCESS_CHECK, ENTITLEMENT_CHECK, GRANT_ACCESS, REVOKE_ACCESS,
    // Wait & timing (5)
    WAIT, WAIT_UNTIL_DATE, WAIT_UNTIL_EVENT, BEST_SEND_TIME, QUIET_HOURS,
    // Personalize (5)
    ASSIGN_OFFER, RESERVE_OFFER, GENERATE_COUPON, PERSONALIZE_CONTENT, NEXT_BEST_ACTION,
    // Govern (6)
    CONSENT_CHECK, SUPPRESSION_CHECK, FREQUENCY_CAP, CHANNEL_PREFERENCE,
    LEGAL_EXCLUSION, INTERACTION_MEMORY,
    // Integrate (6)
    API_WEBHOOK, PUBLISH_EVENT, CREATE_CRM_TASK, CREATE_SERVICE_CASE,
    START_FULFILLMENT, AD_PLATFORM_SYNC,
    // Update data (5)
    UPDATE_PROFILE, ADD_TO_SEGMENT, SET_CAMPAIGN_STATE, UPDATE_PREFERENCE, LOG_INTERACTION,
    // Measure (5)
    TRACK_EVENT, CONVERSION_CHECK, ATTRIBUTION, SURVEY_TRIGGER, ANALYTICS_EXPORT,
    ;

    fun category(): FlowCategory = when (this) {
        START_TRIGGER, EXIT_JOURNEY, PAUSE_JOURNEY, RE_ENTER, JUMP_TO_STEP,
        STOP_CAMPAIGNS -> FlowCategory.JOURNEY_CONTROL
        SEND_EMAIL, SEND_SMS, SEND_PUSH, SEND_WHATSAPP, SEND_IN_APP, WEB_PERSONAL,
        CALL_CENTER_TASK, DIRECT_MAIL -> FlowCategory.COMMUNICATE
        IF_ELSE, AUDIENCE_CHECK, ELIGIBILITY_CHECK, AB_SPLIT, RANDOM_SPLIT,
        CONTROL_GROUP, ML_DECISION, NEXT_BEST_CHANNEL -> FlowCategory.DECIDE
        SCORE, RECOMMEND -> FlowCategory.AI
        ACCESS_CHECK, ENTITLEMENT_CHECK, GRANT_ACCESS, REVOKE_ACCESS -> FlowCategory.ACCESS
        WAIT, WAIT_UNTIL_DATE, WAIT_UNTIL_EVENT, BEST_SEND_TIME,
        QUIET_HOURS -> FlowCategory.WAIT_TIMING
        ASSIGN_OFFER, RESERVE_OFFER, GENERATE_COUPON, PERSONALIZE_CONTENT,
        NEXT_BEST_ACTION -> FlowCategory.PERSONALIZE
        CONSENT_CHECK, SUPPRESSION_CHECK, FREQUENCY_CAP, CHANNEL_PREFERENCE,
        LEGAL_EXCLUSION, INTERACTION_MEMORY -> FlowCategory.GOVERN
        API_WEBHOOK, PUBLISH_EVENT, CREATE_CRM_TASK, CREATE_SERVICE_CASE,
        START_FULFILLMENT, AD_PLATFORM_SYNC -> FlowCategory.INTEGRATE
        UPDATE_PROFILE, ADD_TO_SEGMENT, SET_CAMPAIGN_STATE, UPDATE_PREFERENCE,
        LOG_INTERACTION -> FlowCategory.UPDATE_DATA
        TRACK_EVENT, CONVERSION_CHECK, ATTRIBUTION, SURVEY_TRIGGER,
        ANALYTICS_EXPORT -> FlowCategory.MEASURE
    }
}
